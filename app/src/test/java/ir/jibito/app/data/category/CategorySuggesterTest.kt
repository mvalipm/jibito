    @Test
    fun `یادداشت نوتیفیکیشن از فرهنگ کلمه‌ها کمک می‌گیرد`() {
        val defs = Taxonomy.flatten(Taxonomy.expense)
        val ids = defs.withIndex().associate { (i, d) -> d.code to i.toLong() + 1 }
        val candidates = defs.map { d -> Candidate(ids.getValue(d.code), d.name, d.code.substringBeforeLast('.', "").takeIf { it.isNotEmpty() }?.let { ids[it] }) }
        fun reply(text: String) = ReplyCategoryMatcher.match(text, candidates)?.let { id -> candidates.single { it.id == id }.name }

        assertEquals("لوازم خانگی برقی", reply("کولر گازی خریدم"))
        assertEquals("تاکسی اینترنتی", reply("اسنپ تا فرودگاه"))
        assertEquals("مراقبت مو", reply("آرایشگاه"))
        assertEquals("نظافت", reply("قالیشویی فرش‌ها"))
        assertEquals("کلاس و دوره", reply("شهریه آموزشگاه زبان بچه"))
        assertNull(reply("دادم به علی"))
    }

    @Test
    fun `خالی`() {
        assertNull(CategorySuggester.suggest(null))
        assertNull(CategorySuggester.suggest("  "))
