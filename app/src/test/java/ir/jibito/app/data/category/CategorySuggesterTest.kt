    @Test
    fun `همه‌ی پیشنهادها در ساختار هستند`() {
        for (t in CategorySuggester.targets) assertTrue("پیشنهاد «$t» در ساختار نیست", t in names)
    }

    @Test
    fun `هر کلمه به دسته‌ی خودش می‌رسد (کلمه‌ی کلی‌تر جلویش را نگرفته)`() {
        val wrong = CategorySuggester.keywords.mapNotNull { (word, target) ->
            val got = CategorySuggester.suggest(word)
            if (got == target) null else "«$word» ← «$got» (باید «$target»)"
        }
        assertTrue(wrong.joinToString("\n"), wrong.isEmpty())
    }

    @Test
    fun `کلمه‌ی تکراری در دو دسته نیست`() {
        val dup = CategorySuggester.keywords.groupBy { ReplyCategoryMatcher.normalize(it.first) }
            .filter { it.value.map { p -> p.second }.toSet().size > 1 }.keys
        assertTrue(dup.joinToString(), dup.isEmpty())
    }

